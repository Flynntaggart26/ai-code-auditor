"""Self-contained HTML report (no external assets needed)."""
import html
from datetime import datetime
from .score import compute_score

SEV_COLOR = {"HIGH": "#dc2626", "MEDIUM": "#d97706", "LOW": "#16a34a"}


def to_html(findings: list[dict], target: str = "") -> str:
    s = compute_score(findings)
    rows = []
    for f in sorted(findings, key=lambda x: ({"HIGH": 0, "MEDIUM": 1, "LOW": 2}.get(x["severity"], 3), x["line"])):
        c = SEV_COLOR.get(f["severity"], "#555")
        rows.append(
            "<tr><td><span style='background:{};color:#fff;padding:2px 8px;border-radius:10px;font-size:12px'>{}</span></td>"
            "<td><b>{}</b></td><td>{}</td><td>{}:{}</td><td>{}</td><td>{}</td></tr>".format(
                c, f["severity"], html.escape(f["rule_id"]), html.escape(f["title"]),
                html.escape(str(f["file"])), f["line"], html.escape(str(f["func"])),
                html.escape(f.get("detail", ""))))
    body = "\n".join(rows) if rows else "<tr><td colspan='6'>No findings. Clean!</td></tr>"
    return """<!DOCTYPE html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>SafeCode AI Report — {target}</title>
<style>body{{font-family:system-ui,Segoe UI,Roboto,sans-serif;max-width:1000px;margin:32px auto;padding:0 16px;color:#111}}
.card{{border:1px solid #e5e7eb;border-radius:12px;padding:16px 20px;margin-bottom:16px}}
.score{{font-size:48px;font-weight:800}}table{{width:100%;border-collapse:collapse}}
th,td{{text-align:left;padding:8px;border-bottom:1px solid #eee;font-size:14px}}th{{background:#f8fafc}}</style>
</head><body>
<h1>🛡️ SafeCode AI — Security Report</h1>
<p>Target: <b>{target}</b> · {ts} · {n} findings</p>
<div class="card"><div class="score">{val}/100 ({grade})</div>
<div>HIGH:{h} MEDIUM:{m} LOW:{lo}</div></div>
<div class="card"><table><tr><th>Severity</th><th>Rule</th><th>Title</th><th>Location</th><th>Function</th><th>Detail</th></tr>
{body}</table></div>
<p style="color:#666;font-size:13px">Generated by SafeCode AI (offline AST + taint analysis). Free &amp; open source (MIT).</p>
</body></html>""".format(target=html.escape(target), ts=datetime.now().strftime("%Y-%m-%d %H:%M"),
                          n=len(findings), val=s.value, grade=s.grade, h=s.high, m=s.medium, lo=s.low, body=body)


def write_html(findings: list[dict], path: str, target: str = "") -> None:
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(to_html(findings, target))
